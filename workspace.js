  // --- Document Ingestion & Parsing ---
  async function handleUploadedFiles(files) {
    if (!files || files.length === 0) return;

    // Filter valid files (non-empty and <= 10MB)
    const validFiles = files.filter(f => f.size > 0 && f.size <= 10 * 1024 * 1024);
    if (validFiles.length === 0) {
      showToast('Selected file(s) are empty or exceed the 10MB limit. Please select valid PDF documents.', 'warning');
      return;
    }

    showIndexingProgress(true, 0, 'Uploading files to secure cloud backend...');

    const formData = new FormData();
    formData.append('session_id', state.sessionId);
    validFiles.forEach(file => {
      formData.append('files', file);
    });

    try {
      updateIndexingProgress(50, `Processing ${validFiles.length} file(s) via PyMuPDF...`);
      
      const response = await fetch('http://localhost:8000/api/documents/upload', {
        method: 'POST',
        body: formData
      });

      if (!response.ok) {
        const errData = await response.json().catch(() => ({}));
        throw new Error(errData.detail || `Upload failed with status ${response.status}`);
      }

      const result = await response.json();
      
      // Update local UI state to reflect the server's success
      let successfulCount = 0;
      result.uploaded_documents.forEach(doc => {
        state.documents.push({
          id: doc.document_id,
          name: doc.filename,
          size: 0, // Mocked for now since backend doesn't return size
          type: 'application/pdf',
          pageCount: 1,
          chunks: Array(doc.chunks_created).fill({id: "mock", text: "Chunks are stored securely on the server."})
        });
        
        // Push dummy chunks to allChunks so the UI counts them
        for(let i=0; i<doc.chunks_created; i++) {
            state.allChunks.push({
              id: `chunk-${doc.document_id}-${i}`,
              docId: doc.document_id,
              docName: doc.filename,
              page: 1,
              text: "Content is processed on the server and retrieved during RAG.",
              wordCount: 50
            });
        }
        successfulCount++;
      });

      updateIndexingProgress(100, 'Server-side vector indexing complete.');
      setTimeout(() => {
        showIndexingProgress(false);
        renderDocumentsList();
        renderChunksList();
        updateTelemetry();
        if (successfulCount > 0) {
          showToast(`Successfully uploaded and indexed ${successfulCount} document(s) on the server.`, 'success');
        }
      }, 400);

    } catch (err) {
      console.error('Error parsing document:', err);
      showToast(`Failed to parse documents: ${err.message}`, 'error');
      showIndexingProgress(false);
    }
  }

  // Real PDF extraction using client-side PDF.js
  async function parsePdfFile(file) {
    const arrayBuffer = await file.arrayBuffer();
    const pdf = await pdfjsLib.getDocument({ data: arrayBuffer }).promise;
    const pageCount = pdf.numPages;
    const docId = 'doc-' + Date.now() + '-' + Math.floor(Math.random() * 1000);
    const chunks = [];

    for (let pageNum = 1; pageNum <= pageCount; pageNum++) {
      const page = await pdf.getPage(pageNum);
      const textContent = await page.getTextContent();
      const pageText = textContent.items.map(item => item.str).join(' ').trim();

      if (pageText.length > 0) {
        const words = pageText.split(/\s+/);
        const chunkSize = 250;
        const overlap = 40;

        for (let i = 0; i < words.length; i += (chunkSize - overlap)) {
          const chunkWords = words.slice(i, i + chunkSize);
          const chunkText = chunkWords.join(' ');
          if (chunkText.length > 20) {
            chunks.push({
              id: `chunk-${docId}-${pageNum}-${chunks.length + 1}`,
              docId: docId,
              docName: file.name,
              page: pageNum,
              text: chunkText,
              wordCount: chunkWords.length
            });
          }
        }
      }
    }

    if (chunks.length === 0) {
      chunks.push({
        id: `chunk-${docId}-1-1`,
        docId: docId,
        docName: file.name,
        page: 1,
        text: `[PDF Document: ${file.name}] - Processed ${pageCount} pages. (Scanned or image-only format detected).`,
        wordCount: 15
      });
    }

    return {
      id: docId,
      name: file.name,
      size: file.size,
      type: file.type || 'application/pdf',
      pageCount: pageCount,
      chunks: chunks
    };
  }

  // Text / Markdown / CSV / JSON file reader
  async function parseTextFile(file) {
    const text = await file.text();
    const docId = 'doc-' + Date.now() + '-' + Math.floor(Math.random() * 1000);
    const paragraphs = text.split(/\n\s*\n/).map(p => p.trim()).filter(p => p.length > 20);
    const chunks = [];

    if (paragraphs.length > 0) {
      paragraphs.forEach((p, idx) => {
        chunks.push({
          id: `chunk-${docId}-1-${idx + 1}`,
          docId: docId,
          docName: file.name,
          page: Math.floor(idx / 4) + 1,
          text: p,
          wordCount: p.split(/\s+/).length
        });
      });
    } else {
      chunks.push({
        id: `chunk-${docId}-1-1`,
        docId: docId,
        docName: file.name,
        page: 1,
        text: text.slice(0, 2000),
        wordCount: text.split(/\s+/).length
      });
    }

    return {
      id: docId,
      name: file.name,
      size: file.size,
      type: file.type || 'text/plain',
      pageCount: Math.ceil(chunks.length / 4) || 1,
      chunks: chunks
    };
  }

