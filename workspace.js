  function removeDocument(docId) {
    const docIndex = state.documents.findIndex(d => d.id === docId);
    if (docIndex !== -1) {
      const docName = state.documents[docIndex].name;
      state.documents.splice(docIndex, 1);
      state.allChunks = state.allChunks.filter(c => c.docId !== docId);
      renderDocumentsList();
      renderChunksList();
      updateTelemetry();
      showToast(`Removed ${docName} from workspace.`, 'info');
    }
  }

