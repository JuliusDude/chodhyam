  // --- Inspector & Chunks Rendering ---
  function renderChunksList(filterQuery = '') {
    if (state.allChunks.length === 0) {
      el.inspectorChunksList.innerHTML = '<div class="text-gray-400 text-center py-6">No chunks in memory yet</div>';
      return;
    }

    const filtered = filterQuery
      ? state.allChunks.filter(c => c.text.toLowerCase().includes(filterQuery) || c.docName.toLowerCase().includes(filterQuery))
      : state.allChunks;

    if (filtered.length === 0) {
      el.inspectorChunksList.innerHTML = `<div class="text-gray-400 text-center py-6">No chunks matching "${escapeHtml(filterQuery)}"</div>`;
      return;
    }

    el.inspectorChunksList.innerHTML = '';
    // Show top 60 chunks to preserve peak performance
    const renderedChunks = filtered.slice(0, 60);

    renderedChunks.forEach((chunk) => {
      const card = document.createElement('div');
      const isFocused = state.activeCitationId === chunk.id;
      card.className = `p-3 rounded-lg border transition-all cursor-pointer ${
        isFocused 
          ? 'bg-teal-950/40 border-teal-500 text-white shadow-[0_0_12px_rgba(20,184,166,0.2)]' 
          : 'bg-white/[0.02] border-white/10 hover:border-white/20 text-gray-300'
      }`;
      card.tabIndex = 0;
      card.setAttribute('role', 'article');
      card.setAttribute('aria-label', `Chunk from ${chunk.docName} on page ${chunk.page}`);
      
      card.innerHTML = `
        <div class="flex items-center justify-between text-xs text-teal-400 mb-1 font-mono">
          <span class="truncate max-w-[170px]" title="${escapeHtml(chunk.docName)}">${escapeHtml(chunk.docName)}</span>
          <span>p. ${chunk.page}</span>
        </div>
        <p class="line-clamp-3 text-xs leading-relaxed text-gray-300">${escapeHtml(chunk.text)}</p>
      `;

      const onSelect = () => focusCitation(chunk, 97.5);
      card.addEventListener('click', onSelect);
      card.addEventListener('keydown', (e) => {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          onSelect();
        }
      });

      el.inspectorChunksList.appendChild(card);
    });

    if (filtered.length > 60) {
      const overflowHint = document.createElement('div');
      overflowHint.className = 'text-center py-2 text-xs text-gray-400 font-mono';
      overflowHint.textContent = `+ ${filtered.length - 60} more chunks (use search above to filter)`;
      el.inspectorChunksList.appendChild(overflowHint);
    }
  }

